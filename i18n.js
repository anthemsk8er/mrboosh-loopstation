let lang = 'es';
const listeners = [];

function t(key, vars) {
  const raw = (DICT[lang] && DICT[lang][key]) ?? DICT.es[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : ''));
}

function getLang() {
  return lang;
}

function applyLang(next, { persist = false } = {}) {
  if (next && DICT[next]) {
    lang = next;
    if (persist) localStorage.setItem(I18N_KEY, next);
  }
  document.documentElement.lang = lang;
  document.title = t('app.title');

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
  document.querySelectorAll('[data-title-key]').forEach((el) => {
    el.title = t(el.dataset.titleKey);
  });
  document.querySelectorAll('.lang-btn').forEach((b) => {
    b.setAttribute('aria-pressed', String(b.dataset.lang === lang));
  });
  listeners.forEach((fn) => fn(lang));
}

function onLangChange(fn) {
  listeners.push(fn);
}

